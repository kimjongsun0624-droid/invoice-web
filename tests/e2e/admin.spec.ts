/**
 * 관리자 기능 E2E 테스트 시나리오 (Playwright MCP)
 *
 * 이 파일은 Playwright MCP 도구를 사용하여 실행되는 테스트 시나리오입니다.
 * Claude Code의 Playwright MCP 도구를 통해 실제 브라우저에서 테스트를 수행합니다.
 *
 * 테스트 전제 조건:
 * - 개발 서버가 http://localhost:3000에서 실행 중이어야 함
 * - .env.local에 유효한 NOTION_API_KEY, NOTION_DATABASE_ID, ADMIN_PASSWORD, SESSION_SECRET 설정 필요
 * - Notion 테스트 DB에 검색/정렬/페이지네이션을 검증할 수 있도록 10개 이상의 견적서 데이터 권장
 *   (2026-08-28 기준 실제 테스트 DB에는 1건만 있어 다중 페이지 시나리오는 코드 리뷰로만 검증됨)
 */

/**
 * 테스트 시나리오 1: 미인증 접근 및 로그인 후 원래 경로 복귀
 *
 * 1. browser_navigate: http://localhost:3000/admin/invoices (로그아웃 상태)
 * 2. `/admin-login?next=%2Fadmin%2Finvoices`로 리다이렉트되는지 확인
 * 3. 비밀번호 입력 후 로그인 버튼 클릭
 * 4. 로그인 성공 후 `/admin`이 아니라 원래 요청했던 `/admin/invoices`로 이동하는지 확인
 *
 * 검증 기준:
 * - ✅ 미인증 상태에서 관리자 페이지 접근 시 next 파라미터와 함께 로그인 페이지로 리다이렉트
 * - ✅ 로그인 성공 후 원래 요청 경로로 복귀
 */

/**
 * 테스트 시나리오 2: 로그인 실패 및 무차별 대입 방어
 *
 * 1. 잘못된 비밀번호로 로그인 시도 → "비밀번호가 일치하지 않습니다" 토스트 확인
 * 2. 동일 시도를 5회 연속 반복
 * 3. 6번째 시도(비밀번호 정답 여부 무관) → "로그인 시도 횟수를 초과했습니다..." 메시지 확인
 * 4. 5분 대기 후(또는 서버 재시작 후) 다시 정상 로그인 가능한지 확인
 *
 * 검증 기준:
 * - ✅ 오답 시 명확한 에러 메시지 표시
 * - ✅ IP당 5분에 5회로 로그인 시도가 제한됨
 */

/**
 * 테스트 시나리오 3: 이미 로그인된 상태에서 로그인 페이지 접근
 *
 * 1. 로그인 상태에서 browser_navigate: http://localhost:3000/admin-login
 * 2. 로그인 폼이 보이지 않고 즉시 `/admin`으로 리다이렉트되는지 확인
 *
 * 검증 기준:
 * - ✅ 인증된 사용자가 로그인 페이지에 재접근하면 자동으로 대시보드로 이동
 */

/**
 * 테스트 시나리오 4: 검색 + 하이라이팅 + URL 상태 보존
 *
 * 1. `/admin/invoices` 접근, 검색창에 클라이언트명 일부 입력 (예: "KIDA")
 * 2. 300ms 디바운스 후 URL이 `?query=KIDA`로 갱신되는지 확인 (page/cursor는 없어야 함)
 * 3. 검색 결과 테이블에서 일치하는 텍스트가 `<mark>`로 강조 표시되는지 확인
 * 4. 검색어가 입력된 채로 페이지를 새로고침해도 검색 상태와 페이지 번호가 임의로 리셋되지 않는지 확인
 *
 * 검증 기준:
 * - ✅ 실시간 검색(디바운스) 동작
 * - ✅ 검색어 하이라이팅 표시
 * - ✅ 마운트/새로고침 시 불필요하게 page/cursor가 초기화되지 않음
 */

/**
 * 테스트 시나리오 5: 검색/필터와 정렬의 조합
 *
 * 1. 검색어 또는 상태/날짜 필터를 적용한 상태에서 "발행일" 또는 "총액" 정렬 헤더 클릭
 * 2. URL에 `query`/`status`/`dateFrom`/`dateTo`가 그대로 유지된 채 `sort`/`order`만 바뀌는지 확인
 * 3. 이미 활성화된 정렬 컬럼을 다시 클릭하면 오름차순/내림차순이 토글되는지 확인
 * 4. 필터가 활성 상태일 때도 정렬이 실제로 적용되는지 확인 (검색 결과 순서 변화)
 *
 * 검증 기준:
 * - ✅ 정렬 변경 시 검색/필터 상태가 유지됨
 * - ✅ 동일 컬럼 재클릭 시 정렬 방향 토글
 * - ✅ 검색/필터 활성 중에도 정렬이 실제로 적용됨
 */

/**
 * 테스트 시나리오 6: 페이지네이션 (다중 페이지 데이터 필요)
 *
 * 1. 견적서 목록에서 "다음" 클릭을 반복해 3페이지 이상 이동
 * 2. 각 페이지에서 표시되는 견적서가 이전 페이지와 겹치지 않는지 확인
 * 3. "이전" 버튼을 눌러 3페이지 → 2페이지로 이동 시, 실제로 2페이지에 표시되었던 것과
 *    동일한 데이터가 다시 표시되는지 확인 (커서 히스토리 스택 검증)
 * 4. 1페이지까지 계속 "이전"으로 돌아와 "이전" 버튼이 비활성화되는지 확인
 *
 * 검증 기준:
 * - ✅ Notion 커서 기반 페이지네이션이 앞/뒤 모두 정확한 데이터를 반환
 * - ✅ 페이지 라벨과 실제로 표시되는 데이터가 항상 일치
 */

